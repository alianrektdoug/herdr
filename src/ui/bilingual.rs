#[cfg(test)]
mod tests {
    use super::bilingual;

    #[test]
    fn preserves_english_and_appends_traditional_chinese() {
        assert_eq!(bilingual("New tab"), "New tab(新增分頁)");
        assert_eq!(bilingual("settings"), "settings(設定)");
    }

    #[test]
    fn leaves_machine_or_user_text_unchanged() {
        assert_eq!(bilingual("workspace.create"), "workspace.create");
    }
}
